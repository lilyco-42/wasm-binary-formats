#[test]
fn a_mesh_bigger_than_the_listing_is_counted_not_dumped() {
    let lines = rows("many.stl");
    assert_eq!(
        lines[0],
        "stl\t36184\ttris\t722\tsolid\tThis file was generated by meshio v5.3.5.XXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXX"
    );
    assert_eq!(
        lines
            .iter()
            .filter(|line| line.starts_with("tri\t"))
            .count(),
        16,
        "the list is capped but the count above it is not"
    );
    assert_eq!(lines[18], "cut\ttris\t722");
    assert_eq!(
        lines[19], "box\tmin\t0.000000,0.000000,0.000000\tmax\t4.750000,4.750000,0.750000",
        "the extent covers every triangle, not only the sixteen that are listed"
    );
    assert_eq!(lines[20], "normals\tzero\t0\twrong\t0\tcounted\t722");
    assert_eq!(lines[21], "walked\tend");
}

#[test]
fn a_zeroed_normal_and_a_flipped_one_are_told_apart() {
    let lines = rows("normals.stl");
    assert!(
        lines[0].starts_with("stl\t184\ttris\t2\tsolid\tnormals probe"),
        "{:?}",
        lines[0]
    );
    assert_eq!(
        lines[2],
        "tri\t0\tnormal\t0.000000,0.000000,0.000000\tv0\t0.000000,0.000000,0.000000\tv1\t1.000000,0.000000,0.000000\tv2\t0.000000,1.000000,0.000000\tattr\t0"
    );
    assert_eq!(
        lines[3],
        "tri\t1\tnormal\t-0.577350,-0.577350,-0.577350\tv0\t1.000000,0.000000,0.000000\tv1\t0.000000,1.000000,0.000000\tv2\t0.000000,0.000000,1.000000\tattr\t0"
    );
    assert_eq!(
        lines[lines.len() - 2],
        "normals\tzero\t1\twrong\t1\tcounted\t2",
        "one is missing, one points the other way, and those are different facts"
    );
}

#[test]
fn arithmetic_that_does_not_close_is_not_claimed() {
    // Two triangles under a header that says ten. Calling that a mesh would mean inventing eight
    // triangles, so the identity has to hold before anything at all is said about the file.
    assert_eq!(
        parse(&liar()),
        -2,
        "a lying count is refused, not annotated"
    );

    let mut truncated = fixture("tet.stl");
    truncated.truncate(283);
    assert_eq!(
        parse(&truncated),
        -2,
        "one byte short is no longer arithmetic that closes"
    );
    assert_eq!(
        parse(&fixture("tet.stl")[..234]),
        -2,
        "three of the four triangles are there"
    );
}

#[test]
fn a_foreign_container_that_divides_evenly_is_left_to_its_own_reader() {
    // The regression this gate exists for: an HDF5 superblock with its width bytes zeroed is rightly
    // refused by the HDF5 reader, and was picked up here for a while because a byte at offset 80 of a
    // real file happened to divide evenly by 50.
    let mut crippled = fixture("tree-v0.h5");
    crippled[13] = 0;
    crippled[14] = 0;
    assert_ne!(parse(&crippled), FORMAT_STL, "an HDF5 file is not a mesh");
    for file in [
        "tree-v0.h5",
        "links-v3.h5",
        "word97.doc",
        "photo.heic",
        "rows.avro",
    ] {
        assert_ne!(parse(&fixture(file)), FORMAT_STL, "{file} is not a mesh");
    }
}

#[test]
fn text_stl_and_unrelated_bytes_are_not_claimed_as_binary() {
    // magika's label is about the binary encoding; the ASCII form is a different document, and its
    // bytes read as denormal floats rather than as a unit normal, which is what turns it down here.
    let ascii = b"solid widget\n  facet normal 0 0 1\n    outer loop\n     vertex 0 0 0\n    end loop\n  end facet\nendsolid widget\n";
    assert_ne!(parse(ascii), FORMAT_STL, "an ASCII STL is not this format");
    assert_eq!(parse(&[0u8; 400]), -2, "zeroes name no triangles at all");
    assert_eq!(
        parse(&liar()[..120]),
        -2,
        "below one whole triangle there is nothing to count"
    );
    assert_eq!(parse(b"aaaaaaaa"), -2, "eight bytes name no triangles");

    // A header whose count is huge would ask for a 12 MB mesh from a 184-byte file.
    let mut greedy = liar();
    greedy[80..84].copy_from_slice(&2_000_000_000u32.to_le_bytes());
    assert_ne!(
        parse(&greedy),
        FORMAT_STL,
        "an implausible count is not believed"
    );
}
